"""画像・動画制作ツールへ渡す共通品質基準。実画像の検査を行うコードではない。"""

COMMON_QUALITY = """
【全素材共通の追加品質基準】
1. プロの販促デザイン：Instagram・Web広告に使える品質を目指す。明るさ、清潔感、親しみやすさ、ひと目で伝わるテーマを重視し、イラスト・文字・背景・装飾・余白を調和させる。情報過多も情報不足も避ける。
2. イラスト：記事と各場面に合う表情、動作、姿勢、背景、小物、身体の状態、施術・生活シーンで要点を表す。単なる立ち絵にしない。自然な顔・手指・人体、日本の読者に違和感のない生活環境を描く。説明用の人物は架空のイメージとし、実在スタッフ、店舗内装、症例、効果の証拠として捏造しない。
3. 情報量：タイトルだけで終わらず、必要な短い説明やポイントを添える。悩み・原因・対策・メリット・注意点・施術内容・おすすめポイントから、その場面に必要なものを記事に基づいて要約する。画像だけでも要点を理解できるようにする。記事にない事実・効果・数値を補わない。
4. 配置：文字専用領域とイラスト領域を分離し、顔・身体・重要な小物へ文字を重ねない。高コントラスト、十分な余白、大きなタイトル、タイトルの約80％のサブテキストでスマートフォンでも読めるようにする。収まらなければ領域と短文を再設計する。
5. 日本語：意味のまとまりで改行し、単語・熟語・正式名称・数字と単位を分断しない。「パーソナルトレーニング」を途中で切らない。助詞だけが行頭・行末に孤立する改行、文字切れ、誤字を避ける。各行の幅、中央揃え、余白、重心を整える。
6. カルーセル：全画像を1作品として、色調・フォント・タッチ・人物・余白・タイトル位置・文字配置・装飾・ブランドイメージを統一する。文字の基準位置を保ちながらイラスト領域内の構図や視点を変え、同じレイアウトのコピーにしない。
7. 表紙：最も重要な画像として、強いが誇張しないキャッチコピー、明確なテーマ、内容を表すイラスト、読みやすい文字を配置。「誰のための、どんな内容か」がひと目で分かり、続きを見たくなるようにする。
8. 最終ページ：要点のまとめと、店舗・サービスへの優しいCTAを入れる。「こんなお悩みがある方はご相談ください」「無理なく始めてみませんか？」など内容に合う誘導を使う。提供された正式名称や予約・相談情報を読みやすく配置し、未提供の連絡先・URL・サービスは作らない。
9. 販促視点：続きを見たくなるか、自分の悩みと思えるか、サービスに興味を持てるか、保存したい情報かを確認する。煽りや過剰な広告表現を避ける。
10. 動画構成：表紙→悩み・問題提起→原因→解決策・ポイント→サービス紹介→CTAを基本にする。記事に該当情報がない段階は省略・再構成し、捏造しない。静止画の単純連結で終わらず、自然な動き、視線誘導、切り替えで編集する。
11. 冒頭：最初の1〜3秒で自分に関係する内容と伝わる表紙にし、表紙自体は3.5〜4秒保持して読める時間を確保する。開始フレームから完成した明るい画面を表示し、黒画面を入れない。
12. テロップ：ナレーションを使用せず、伝える内容を日本語のタイプライター風テロップで表示する。全文の改行と位置を先に確定し、文字が増えても折り返しや位置が跳ねないようにする。全文表示後に読める時間を設け、読み終わる前に切り替えない。
13. BGM：健康・美容・リラクゼーション・店舗紹介に合う、明るい・穏やか・少しポップ・前向きな曲調。心地よく控えめな音量で映像を支え、主張しすぎず途切れない。使用権を確認できる音源を使う。
14. Reels・TikTok：縦型スマートフォン視聴を前提に、上下左右に操作UI用の安全余白を確保する。重要な文字や人物を端に置かず、読める時間を保った上でテンポよく間延びを防ぐ。
15. YouTube：16:9横型専用に構図を設計する。縦型動画の単純変換・引き伸ばし・左右への余白追加で済ませない。人物・イラスト・タイトル・説明テロップを左右の広さを活用して再配置する。
16. 名称：提供された店舗情報を優先し、指定の正式名称を一字一句守る。略称、英語、別名称へ勝手に変えない。正式名称を文字数制限で切らない。
17. 品質検査：誤字脱字、漢字、文字化け、文字切れ、単語途中改行、不自然な日本語、手指・顔・身体、文字との重なり、見切れ、余白、情報量、色、スマートフォン可読性、ブランド名を確認し、不具合を修正する。
18. 最終確認：プロのグラフィックデザイナー、プロのイラストレーター、SNSマーケティング担当者の3視点で、即時理解、魅力、内容と絵の一致、可読性、十分な情報、広告感の強さ、保存・シェア・予約への自然な導線を確認する。
19. 工程：①元データ理解→②伝える内容整理→③デザイン構成→④生成→⑤文字・配置・人物確認→⑥マーケティング確認→⑦修正→⑧再検品して最終化。一度生成したものを無条件に完成としない。静止画は実物を拡大・縮小確認し、動画は書き出し後に通し再生して音と全場面を検査する。確認できない場合に確認済みと称さない。
20. 最重要：記事をただ画像化せず、視覚的に再構成したコンテンツにする。記事を読まなくても悩み・原因・解決方法・確認できるサービスのメリットが理解できることを目指す。高品質なチャット生成画像に求める明るさ、魅力、情報量、可読性、全体バランスを重視する。
"""


def apply_quality_rules(prompts: dict, brand_name: str = "") -> dict:
    """単体コピーでも品質指示が欠けないよう、全素材へ添付する。"""
    brand = str(brand_name or "").strip()
    brand_rule = (
        f"指定された正式名称は『{brand}』。この表記を省略・翻訳・変更しない。"
        if brand else "正式名称は元記事に明記されたものだけを使い、不明なら店舗名や連絡先を創作しない。"
    )
    for key, value in prompts.items():
        items = value if isinstance(value, list) else [value]
        for item in items:
            if not isinstance(item, dict) or "prompt" not in item:
                continue
            item["prompt"] += "\n" + COMMON_QUALITY + "\n" + brand_rule
            if key == "instagram_carousel":
                number = item.get("slide")
                item["prompt"] += "\n全9枚で共通の配色・人物設定・書体・装飾・余白を先に決め、各枚を独立ファイルで制作する。"
                if number == 1:
                    item["prompt"] += "この1枚は表紙。対象読者と記事のテーマが即座に分かるキャッチコピーを主役にする。"
                elif number == 9:
                    item["prompt"] += "この9枚目は最終ページ。記事の要点と優しい相談・予約CTAを配置する。" + brand_rule
            elif key in ("reel_cover", "tiktok_cover", "youtube_thumbnail"):
                item["prompt"] += "\n表紙として、対象読者とテーマが一目で分かる構図を優先する。"
    return prompts
